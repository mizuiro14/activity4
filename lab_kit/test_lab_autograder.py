import time
import importlib
import pytest
from unittest.mock import patch

APP_MODULE_NAME = "app"  # rename app_template.py -> app.py


@pytest.fixture
def client():
    mod = importlib.import_module(APP_MODULE_NAME)
    importlib.reload(mod)
    mod.app.config["TESTING"] = True
    with mod.app.test_client() as c:
        yield c, mod


def test_level1_basic_order(client):
    c, mod = client
    with patch("random.random", return_value=0.9):  # forces success
        resp = c.post("/orders", json={"order_id": "A1", "amount": 100})
    assert resp.status_code == 200
    data = resp.get_json()
    assert data.get("status") == "success"
    assert data.get("order_id") == "A1"


def test_level2_idempotency(client):
    c, mod = client
    headers = {"Idempotency-Key": "key-123"}
    with patch("random.random", return_value=0.9):
        r1 = c.post("/orders", json={"order_id": "A2", "amount": 50}, headers=headers)
        r2 = c.post("/orders", json={"order_id": "A2", "amount": 50}, headers=headers)
    assert r1.status_code == 200 and r2.status_code == 200
    assert r1.get_json()["charge_id"] == r2.get_json()["charge_id"], (
        "A repeated request with the same Idempotency-Key must not create a second charge."
    )


def test_level2_retry_recovers(client):
    c, mod = client
    mod.payment_gateway.latency = 0.01
    # First two attempts fail, third succeeds — your retry logic must catch this.
    with patch("random.random", side_effect=[0.01, 0.01, 0.9]):
        resp = c.post("/orders", json={"order_id": "A3", "amount": 75})
    assert resp.status_code == 200, "A transient failure should be retried, not surfaced to the caller."
    assert resp.get_json()["status"] == "success"


def test_level3_async_notification(client):
    c, mod = client
    mod.notifications.send_delay = 0.5
    with patch("random.random", return_value=0.9):
        start = time.time()
        resp = c.post("/orders", json={"order_id": "A4", "amount": 20})
        elapsed = time.time() - start
    assert resp.status_code == 200
    assert elapsed < 0.45, (
        "The /orders response should return before the notification finishes sending "
        "(run it in the background, not inline)."
    )
    time.sleep(0.7)
    assert len(mod.notifications.sent_log) >= 1, (
        "The confirmation should still be sent eventually, just without blocking the response."
    )


def test_level4_circuit_breaker(client):
    c, mod = client
    mod.payment_gateway.latency = 0.01
    with patch("random.random", return_value=0.01):  # force every gateway call to fail
        for i in range(3):
            c.post("/orders", json={"order_id": f"B{i}", "amount": 10})
        start = time.time()
        resp = c.post("/orders", json={"order_id": "B4", "amount": 10})
        elapsed = time.time() - start
    assert resp.status_code == 503, "After repeated failures the circuit should open and fail fast."
    assert elapsed < 0.05, "An open circuit must NOT call the gateway again — it should fail immediately."
